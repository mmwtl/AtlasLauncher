"""Usage: python3 make_donate_qr.py app/src/main/res/drawable/ic_donate_qr.xml

Needs `pip install qrcode`. Draws the CloudTips donation QR code as a VectorDrawable: the same
matrix as the CloudTips page's image (version 4, level Q, mask 2) with its logo, a black disk
with two white slanted capsules, over the centre modules. Level Q restores what the logo hides.
"""
import math
import sys

import qrcode

URL = 'https://pay.cloudtips.ru/p/5c3a9385'
QUIET = 4
# Logo in module units from the code's top-left corner, measured on the CloudTips image.
LOGO_RADIUS = 3.0
CAPSULE_OFFSET = 0.85
CAPSULE_LENGTH = 3.1
CAPSULE_WIDTH = 1.04
CAPSULE_ANGLE = -42.2


def fmt(value):
    return ('%.3f' % value).rstrip('0').rstrip('.')


def modules():
    code = qrcode.QRCode(version=4, error_correction=qrcode.constants.ERROR_CORRECT_Q,
                         border=0, mask_pattern=2)
    code.add_data(URL)
    code.make(fit=False)
    return code.get_matrix()


def module_paths(matrix):
    """Black runs as one path per few rows; lint flags paths longer than 800 characters."""
    size = len(matrix)
    centre = size / 2
    paths = []
    parts = []
    for row in range(size):
        if row % 5 == 0 and parts:
            paths.append(''.join(parts))
            parts = []
        col = 0
        while col < size:
            if not matrix[row][col] or math.hypot(col + .5 - centre, row + .5 - centre) \
                    < LOGO_RADIUS:
                col += 1
                continue
            start = col
            while col < size and matrix[row][col] and math.hypot(
                    col + .5 - centre, row + .5 - centre) >= LOGO_RADIUS:
                col += 1
            parts.append('M%s,%sh%sv1h-%sz' % (start + QUIET, row + QUIET, col - start,
                                               col - start))
    paths.append(''.join(parts))
    return paths


def disk_path(cx, cy, radius):
    return 'M%s,%sa%s,%s 0 1,1 %s,0a%s,%s 0 1,1 -%s,0z' % (
        fmt(cx - radius), fmt(cy), fmt(radius), fmt(radius), fmt(2 * radius),
        fmt(radius), fmt(radius), fmt(2 * radius))


def capsule_path(cx, cy):
    angle = math.radians(CAPSULE_ANGLE)
    ux, uy = math.cos(angle), math.sin(angle)
    vx, vy = -uy, ux
    half = CAPSULE_LENGTH / 2 - CAPSULE_WIDTH / 2
    r = CAPSULE_WIDTH / 2
    ax, ay = cx - ux * half, cy - uy * half
    bx, by = cx + ux * half, cy + uy * half
    return 'M%s,%sL%s,%sA%s,%s 0 0,0 %s,%sL%s,%sA%s,%s 0 0,0 %s,%sz' % (
        fmt(ax + vx * r), fmt(ay + vy * r), fmt(bx + vx * r), fmt(by + vy * r),
        fmt(r), fmt(r), fmt(bx - vx * r), fmt(by - vy * r),
        fmt(ax - vx * r), fmt(ay - vy * r), fmt(r), fmt(r),
        fmt(ax + vx * r), fmt(ay + vy * r))


def main():
    matrix = modules()
    size = len(matrix) + 2 * QUIET
    centre = size / 2
    capsules = capsule_path(centre - CAPSULE_OFFSET, centre) \
        + capsule_path(centre + CAPSULE_OFFSET, centre)
    black = module_paths(matrix) + [disk_path(centre, centre, LOGO_RADIUS)]
    with open(sys.argv[1], 'w') as out:
        out.write('''<?xml version="1.0" encoding="utf-8"?>
<!-- %s, generated by tools/make_donate_qr.py; rerun it instead of editing. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="%sdp"
    android:height="%sdp"
    android:viewportWidth="%s"
    android:viewportHeight="%s">
    <path
        android:fillColor="#FFFFFF"
        android:pathData="M0,0h%sv%sh-%sz" />
%s    <path
        android:fillColor="#FFFFFF"
        android:pathData="%s" />
</vector>
''' % (URL, size * 4, size * 4, size, size, size, size, size, ''.join('''    <path
        android:fillColor="#000000"
        android:pathData="%s" />
''' % path for path in black), capsules))


if __name__ == '__main__':
    main()
